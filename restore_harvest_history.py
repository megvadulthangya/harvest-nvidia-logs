#!/usr/bin/env python3
"""Restore persistent harvest history from a GitHub results branch.

Only the cross-run state is restored:
  * history/ (state.json + historical README snapshots)
  * driver-changelog.md

The current README and per-build result directories are deliberately not
restored; they are regenerated by the current run.
"""

from __future__ import annotations

import argparse
import base64
import os
import shutil
import subprocess
import tempfile
from pathlib import Path


PERSISTENT_PATHS = ("history", "driver-changelog.md")


def _git_env(token: str | None) -> dict[str, str]:
    env = os.environ.copy()
    env["GIT_TERMINAL_PROMPT"] = "0"
    if token:
        auth = base64.b64encode(f"x-access-token:{token}".encode()).decode()
        env["GIT_CONFIG_COUNT"] = "1"
        env["GIT_CONFIG_KEY_0"] = "http.https://github.com/.extraheader"
        env["GIT_CONFIG_VALUE_0"] = f"AUTHORIZATION: basic {auth}"
    return env


def restore_from_directory(previous_results: Path, harvest_dir: Path) -> list[str]:
    """Copy persistent state from an already checked-out results tree."""
    previous_results = previous_results.resolve()
    harvest_dir = harvest_dir.resolve()
    harvest_dir.mkdir(parents=True, exist_ok=True)
    restored: list[str] = []

    for name in PERSISTENT_PATHS:
        source = previous_results / name
        if not source.exists():
            continue
        destination = harvest_dir / name
        if destination.is_dir() and not destination.is_symlink():
            shutil.rmtree(destination)
        elif destination.exists() or destination.is_symlink():
            destination.unlink()

        if source.is_dir():
            shutil.copytree(source, destination)
        else:
            shutil.copy2(source, destination)
        restored.append(name)

    return restored


def restore_harvest_history(
    repository: str,
    results_branch: str,
    harvest_dir: Path,
    token: str | None = None,
) -> list[str]:
    """Fetch a results branch and restore its persistent harvest state.

    A missing results branch is a normal first-run condition and returns an
    empty list. Authentication and network failures against an existing
    branch raise RuntimeError rather than silently discarding history.
    """
    if not repository or repository.count("/") != 1:
        raise RuntimeError(f"Invalid GitHub repository name: {repository!r}")
    if not results_branch or results_branch.startswith("-"):
        raise RuntimeError(f"Invalid results branch name: {results_branch!r}")
    ref_check = subprocess.run(
        ["git", "check-ref-format", f"refs/heads/{results_branch}"],
        text=True,
        capture_output=True,
        check=False,
    )
    if ref_check.returncode != 0:
        raise RuntimeError(f"Invalid results branch name: {results_branch!r}")

    env = _git_env(token)
    remote_url = f"https://github.com/{repository}.git"
    ref = f"refs/heads/{results_branch}"

    with tempfile.TemporaryDirectory(prefix="harvest-history-") as tmp_name:
        tmp = Path(tmp_name)
        probe = subprocess.run(
            ["git", "ls-remote", "--heads", remote_url, ref],
            text=True,
            capture_output=True,
            env=env,
            check=False,
        )
        if probe.returncode != 0:
            detail = (probe.stderr or probe.stdout).strip()
            raise RuntimeError(f"Cannot query results branch {ref}: {detail}")
        if not probe.stdout.strip():
            print(f"[history] no previous results branch ({results_branch}); first run")
            return []

        subprocess.run(["git", "init", "--quiet", str(tmp)], env=env, check=True)
        subprocess.run(
            ["git", "-C", str(tmp), "remote", "add", "origin", remote_url],
            env=env,
            check=True,
        )
        fetch = subprocess.run(
            ["git", "-C", str(tmp), "fetch", "--quiet", "--depth=1", "--no-tags",
             "origin", ref],
            text=True,
            capture_output=True,
            env=env,
            check=False,
        )
        if fetch.returncode != 0:
            detail = (fetch.stderr or fetch.stdout).strip()
            raise RuntimeError(f"Cannot fetch results branch {results_branch}: {detail}")
        subprocess.run(
            ["git", "-C", str(tmp), "checkout", "--quiet", "--detach", "FETCH_HEAD"],
            env=env,
            check=True,
        )
        restored = restore_from_directory(tmp, harvest_dir)

    print(
        "[history] restored " + (", ".join(restored) if restored else
                                  "no history/changelog files")
        + f" from {repository}:{results_branch}"
    )
    return restored


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repository", default=os.environ.get("GITHUB_REPOSITORY"))
    parser.add_argument("--results-branch", required=True)
    parser.add_argument("--harvest-dir", type=Path, required=True)
    parser.add_argument("--token", default=os.environ.get("GITHUB_TOKEN"))
    args = parser.parse_args()
    try:
        restore_harvest_history(
            args.repository or "",
            args.results_branch,
            args.harvest_dir,
            args.token,
        )
    except Exception as exc:  # noqa: BLE001 - concise CLI failure
        parser.exit(1, f"ERROR: {exc}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
